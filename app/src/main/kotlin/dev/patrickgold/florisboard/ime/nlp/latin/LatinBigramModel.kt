package dev.patrickgold.florisboard.ime.nlp.latin

import kotlin.math.ln

/**
 * Static next-word statistics for English: which words follow each word and how often, plus enough totals to tell
 * whether a word fits after another one at all.
 *
 * Loaded from ime/dict/bigrams.tsv, generated by utils/gen_dict_assets.py from the SymSpell English bigram
 * dictionary. Each word's followers are kept in parallel arrays ordered by probability, plus an alphabetical index
 * so a single pair can be looked up quickly during autocorrect, where it is asked for thousands of candidates.
 */
class LatinBigramModel private constructor(private val entries: Map<String, Entry>) {
    class Followers(val words: Array<String>, val probabilities: FloatArray) {
        private val alphabetical: IntArray = words.indices.sortedBy { words[it] }.toIntArray()

        fun probabilityOf(word: String): Double {
            var lo = 0
            var hi = alphabetical.size - 1
            while (lo <= hi) {
                val mid = (lo + hi) ushr 1
                val index = alphabetical[mid]
                val cmp = words[index].compareTo(word)
                when {
                    cmp < 0 -> lo = mid + 1
                    cmp > 0 -> hi = mid - 1
                    else -> return probabilities[index].toDouble()
                }
            }
            return 0.0
        }
    }

    /**
     * @property followers The words seen after this one, null if none.
     * @property unseenCeiling The highest probability a follower missing from [followers] could have.
     * @property marginal How likely this word is as the second word of any pair, 0 if it never follows anything.
     */
    private class Entry(val followers: Followers?, val unseenCeiling: Double, val marginal: Double)

    val size: Int
        get() = entries.size

    fun followersOf(word: String): Followers? = entries[word]?.followers

    /** P([word] | [previous]), or 0 if the pair is not among the stored followers. */
    fun probability(previous: String, word: String): Double {
        return entries[previous]?.followers?.probabilityOf(word) ?: 0.0
    }

    /**
     * How much more (positive) or less (negative) likely [word] is right after [previous] than in general, as a
     * base 2 logarithm. "the was" is far below zero, "it was" far above. A pair missing from the data only counts
     * as evidence against [word] when it would have been common enough to be listed, otherwise this returns 0.
     *
     * @return The lift, or null if either word is unknown to the model.
     */
    fun lift(previous: String, word: String): Double? {
        val entry = entries[previous] ?: return null
        val marginal = entries[word]?.marginal ?: return null
        if (marginal <= 0.0 || entry.unseenCeiling <= 0.0) return null
        val p = entry.followers?.probabilityOf(word) ?: 0.0
        if (p > 0.0) return ln(p / marginal) / LN2
        return minOf(0.0, ln(entry.unseenCeiling / marginal) / LN2)
    }

    /** True if [word] is known to follow other words, so its fit after a word can be judged at all. */
    fun isKnownFollower(word: String): Boolean = (entries[word]?.marginal ?: 0.0) > 0.0

    companion object {
        private val LN2 = ln(2.0)

        val Empty = LatinBigramModel(emptyMap())

        /**
         * Parses lines of the form `word<TAB>unseen ppm<TAB>marginal ppb<TAB>follower:ppm,follower:ppm`. Comment
         * lines start with `#`, malformed lines and cells are skipped. Words are shared between lines, so common
         * followers like "the" are stored once.
         */
        fun parse(text: String): LatinBigramModel {
            val result = HashMap<String, Entry>()
            val pool = HashMap<String, String>()
            fun shared(word: String): String = pool.getOrPut(word) { word }
            for (line in text.lineSequence()) {
                if (line.isEmpty() || line[0] == '#') continue
                val columns = line.split('\t')
                if (columns.size != 4 || columns[0].isEmpty()) continue
                val unseen = columns[1].toDoubleOrNull() ?: continue
                val marginal = columns[2].toDoubleOrNull() ?: continue
                var followers: Followers? = null
                if (columns[3].isNotEmpty()) {
                    val cells = columns[3].split(',')
                    val words = ArrayList<String>(cells.size)
                    val probabilities = ArrayList<Float>(cells.size)
                    for (cell in cells) {
                        val colon = cell.lastIndexOf(':')
                        if (colon <= 0) continue
                        val ppm = cell.substring(colon + 1).toIntOrNull() ?: continue
                        words.add(shared(cell.substring(0, colon)))
                        probabilities.add(ppm / 1_000_000f)
                    }
                    if (words.isNotEmpty()) {
                        followers = Followers(words.toTypedArray(), probabilities.toFloatArray())
                    }
                }
                result[shared(columns[0])] = Entry(followers, unseen / 1_000_000.0, marginal / 1_000_000_000.0)
            }
            return LatinBigramModel(result)
        }
    }
}
